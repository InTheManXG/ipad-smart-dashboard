  context.fetch=async url=>url.endsWith('/control') ? {ok:false,status:403} : new Promise(resolve=>{resolveOldPoll=resolve;});
  const stalePermissionPoll=context.refreshMusic();
  await context.controlMusic('next');
  resolveOldPoll({ok:true,json:async()=>({...song,controlAllowed:true})});
  await stalePermissionPoll;
  assert.equal(nodes.get('music-control-result').textContent,permissionMessage);
