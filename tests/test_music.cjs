// 覆盖暂停、拖动、前奏、间奏和断线，不依赖真实播放器。
const vm = require('node:vm');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const nodes = new Map();
const node = () => ({textContent:'',className:'',style:{},dataset:{},children:[],setAttribute(name,value){this[name]=value;},replaceChildren(...children){this.children=children;}});
const context = vm.createContext({document:{hidden:false,addEventListener(){},createElement:node,getElementById(id){if(!nodes.has(id))nodes.set(id,node());return nodes.get(id);}},sessionStorage:{getItem(){return '';}},performance:{now(){return 0;}},setInterval(){},requestAnimationFrame(){},setTimeout,clearTimeout,AbortController});
vm.runInContext(fs.readFileSync('web/music.js','utf8'),context);
const frame = (snapshot, elapsed = 0) => context.lyricFrame(snapshot, elapsed);
const song = {state:'ready',trackId:'a'.repeat(64),title:'歌',artist:'歌手',source:'网易云音乐',position:0,duration:100,playing:true,lyricsState:'ready',lines:[{time:2,text:'第一句'},{time:5,text:'第二句'},{time:8,text:''},{time:12,text:'第三句'}]};
assert.equal(frame(song).current,'前奏');
assert.equal(frame(song,3).current,'第一句');
assert.equal(frame(song,5).current,'第二句');
assert.equal(frame({...song,position:8}).current,'间奏');
assert.equal(frame({...song,position:12}).current,'第三句');
assert.equal(frame({...song,position:2,playing:false},6).current,'第一句');
assert.equal(frame(song,9).state,'未连接');
assert.equal(frame({...song,lyricsState:'missing'}).current,'暂无匹配的时间轴歌词');
assert.equal(frame({...song,state:'idle'}).current,'♪');
assert.equal(frame({...song,position:5}).previous,'第一句');
assert.equal(frame({...song,position:2}).next,'第二句');
assert.equal(context.musicTime(65.9),'1:05');
assert.equal(context.musicTime(3600),'60:00');
assert.equal(context.musicTime(undefined),'--:--');
assert.equal(context.musicTime(-1),'--:--');
assert.equal(frame({...song,position:99},5).position,100);
assert.equal(frame({...song,position:25,playing:false},5).position,25);
assert.equal(frame({...song,lyricsState:'missing',position:25},1).position,26);
assert.equal(frame(song,9).position,undefined);
context.testSong = {...song,lyricsState:'missing',position:25};
vm.runInContext('musicSnapshot = testSong; renderMusic()',context);
assert.equal(nodes.get('music-progress').value,25);
assert.equal(nodes.get('music-progress').max,100);
assert.equal(nodes.get('music-elapsed').textContent,'0:25');
assert.equal(nodes.get('music-duration').textContent,'1:40');
vm.runInContext('musicSnapshot = null; renderMusic()',context);
assert.equal(nodes.get('music-progress').value,0);
assert.equal(nodes.get('music-elapsed').textContent,'--:--');
assert.equal(nodes.get('music-duration').textContent,'--:--');
const draw = position => context.renderLyrics(song,frame({...song,position}));
draw(4.9);
const track = nodes.get('lyric-track'), first = track.children[1];
draw(5.1);
assert.equal(track.className,'smooth');
assert.equal(track.children[1],first);
assert.equal(track.children[2].className,'lyric-line active');
assert.equal(track.style.transform,'translateY(calc(-1 * var(--lyric-step)))');
context.renderLyrics({...song},frame({...song,position:5.2}));
assert.equal(track.children[1],first, '轮询不能重建歌词节点');
draw(12);
assert.equal(track.className,'','拖动跳过多行时直接定位');
draw(2);
assert.equal(track.className,'','向后拖动直接定位');
context.renderLyrics({...song,title:'新歌'},frame({...song,title:'新歌',position:2}));
assert.equal(track.className,'');
assert.notEqual(track.children[1],first);
context.renderLyrics(null,frame(null));
assert.equal(track.children.length,1);
assert.equal(track.children[0].textContent,'♪');
(async () => {
  let now = 1000;
  context.performance.now = () => now;
  context.sessionStorage.getItem = () => 'test-only';
  // 模拟往返一秒的网络，服务端进度为请求中点的位置。
  context.fetch = async () => {now += 1000; return {ok:true,json:async()=>({...song,position:25})};};
  await context.refreshMusic();
  assert.equal(nodes.get('music-progress').value,25.5,'播放中补偿回程的半秒');
  assert.equal(nodes.get('music-toggle')['aria-label'],'暂停');
  assert.equal(nodes.get('music-next').disabled,false);
  now += 500;
  context.animateMusic();
  assert.equal(nodes.get('music-elapsed').textContent,'0:26','跨秒更新不等待网络轮询');
  context.fetch = async () => {now += 1000; return {ok:true,json:async()=>({...song,position:25,playing:false})};};
  await context.refreshMusic();
  assert.equal(nodes.get('music-progress').value,25,'暂停不能补偿成继续播放');
  assert.equal(nodes.get('music-toggle')['aria-label'],'播放');
  let resolveCommand, sent;
  const stateFetch = context.fetch;
  context.fetch = async (url, options) => {
    if (url.endsWith('/control')) {sent=JSON.parse(options.body);return new Promise(resolve=>{resolveCommand=resolve;});}
    return stateFetch();
  };
  const command = context.controlMusic('play');
  assert.equal(sent.action,'play');
  assert.equal(sent.trackId,song.trackId);
  assert.equal(nodes.get('music-next').disabled,true,'等待回执时禁用连点');
  await context.controlMusic('next');
  assert.equal(sent.action,'play','连点不产生第二个请求');
  resolveCommand({ok:true,json:async()=>({ok:true})});
  await command;
  assert.equal(nodes.get('music-control-result').textContent,'');
  context.fetch = async()=>({ok:false});
  await context.controlMusic('next');
  assert.match(nodes.get('music-control-result').textContent,/未能确认/);
  context.fetch = async () => {now += 1000; return {ok:true,json:async()=>({...song,title:'新歌',position:0})};};
  await context.refreshMusic();
  assert.equal(nodes.get('music-progress').value,.5,'切歌使用新时间轴');
  now += 9000;
  context.animateMusic();
  assert.equal(nodes.get('music-elapsed').textContent,'--:--','断线不持续外推');
  assert.equal(nodes.get('music-next').disabled,true,'断线禁用控制');
  console.log('歌词时间轴、动画、网络耗时补偿、暂停及跨秒显示验证通过');
})().catch(error=>{console.error(error);process.exitCode=1;});
